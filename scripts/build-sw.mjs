// Writes public/sw.js from src/lib/pwa/service-worker.js, stamped with a hash
// of everything that goes into the client build. Runs as part of `prebuild`.
//
// Why: the browser decides whether a new version exists by comparing the
// bytes of /sw.js. A hand-written worker that never changes means an open or
// installed app never hears about a deploy. With the stamp, any change to the
// app changes the worker, and an unchanged rebuild produces the same bytes
// (so a redeploy of the same code doesn't ask anyone to refresh).
//
// No network, no environment variables: the hash is of files on disk.

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src', 'lib', 'pwa', 'service-worker.js');
const out = join(root, 'public', 'sw.js');

/** What ends up in the browser. Tests don't. */
const inputs = ['src', 'public', 'package-lock.json', 'next.config.ts', 'postcss.config.mjs'];

function walk(p) {
  if (p === out) return [];
  if (statSync(p).isDirectory())
    return readdirSync(p)
      .filter((n) => !n.startsWith('.'))
      .flatMap((n) => walk(join(p, n)));
  return /\.test\.tsx?$/.test(p) ? [] : [p];
}

const files = inputs
  .map((p) => join(root, p))
  .flatMap(walk)
  .map((p) => relative(root, p).split('\\').join('/'))
  .sort();

const hash = createHash('sha256');
for (const file of files) {
  hash.update(file);
  hash.update('\0');
  hash.update(readFileSync(join(root, file)));
  hash.update('\0');
}
const build = hash.digest('hex').slice(0, 16);

writeFileSync(
  out,
  `// Work Optional build ${build} — generated by scripts/build-sw.mjs from\n` +
    `// src/lib/pwa/service-worker.js. Edit that file, not this one.\n` +
    readFileSync(source, 'utf8'),
);
console.log(`sw.js: build ${build} (${files.length} files)`);
